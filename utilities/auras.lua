---Combine all tables into one and return the result.
---@param ... table<SpellID, SpellName>
---@return table<SpellID, SpellName>
local function CombineTables(...)
    local result = {}
    for _, table in ipairs({...}) do
        for k, v in pairs(table) do
            result[k] = v
        end
    end
    return result
end

if addon_data.utils.IsClassicWow() then
    AURAS = CombineTables(CLASSIC_AURAS, COMMON_AURAS, CLASSIC_TBC_AURAS, CLASSIC_WRATH_AURAS)
elseif addon_data.utils.IsTbcWow() then
    AURAS = CombineTables(TBC_AURAS, COMMON_AURAS, CLASSIC_TBC_AURAS, TBC_WRATH_AURAS)
elseif addon_data.utils.IsWrathWow() then
    AURAS = CombineTables(WRATH_AURAS, COMMON_AURAS, CLASSIC_WRATH_AURAS, TBC_WRATH_AURAS)
end

---Returns `true` if `spellID` is registered as being a spell that modifies attack speed,
---otherwise returns `false`.
---@param spellID SpellID
---@return boolean
function auras.IsSpeedAura(spellID)
    return AURAS[spellID] and true or false
end

